#!/usr/bin/env node
// Generates the Kiro flavour of the harness (.kiro/) from the Claude Code source of truth (.claude/).
// Derived files (skills, manual steering from commands, UI-design agent prompt) are regenerated;
// hand-written Kiro files (always/fileMatch steering, agents, hooks, MCP settings) are left untouched.
// Kiro ignores symlinked steering files, so everything is copied as real files.
import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync, statSync, rmSync, chmodSync } from "node:fs";
import { resolve, dirname, join, extname, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = resolve(ROOT, ".claude");
const DST = resolve(ROOT, ".kiro");
const pkg = JSON.parse(readFileSync(resolve(ROOT, "package.json"), "utf8"));
const check = process.argv.includes("--check");

const TEXT_TRANSFORM_FILES = /(SKILL\.md|references\/.+\.md|implement-and-evaluate-tmux\/scripts\/.+\.sh)$/;

// Ordered literal replacements applied to skill instructions and tmux scripts.
const REPLACEMENTS = [
  ['claude --dangerously-skip-permissions "/implement-and-evaluate $ie_input"',
    '${FDD_AGENT_CLI:-kiro-cli} chat --agent fdd --no-interactive --trust-all-tools "Use the implement-and-evaluate skill with this input: $ie_input"'],
  ['exec claude --dangerously-skip-permissions "/implement-and-evaluate F<ID> <tail>"',
    'exec kiro-cli chat --agent fdd --no-interactive --trust-all-tools "Use the implement-and-evaluate skill with this input: F<ID> <tail>"'],
  ["`claude /implement-and-evaluate F<ID>`", "`kiro-cli chat --agent fdd` running the `implement-and-evaluate` skill for F<ID>"],
  ["exec `claude /implement-and-evaluate F<ID> <tail>`", "exec `kiro-cli chat --agent fdd` (implement-and-evaluate skill)"],
  ["claude /implement-and-evaluate", "kiro-cli chat --agent fdd /implement-and-evaluate"],
  ["claude TUI", "kiro-cli session"],
  ["Main Claude session", "main Kiro session"],
  ["Main Claude", "main Kiro session"],
  ["on `claude` exit", "on `kiro-cli` exit"],
  ["On `claude` exit", "On `kiro-cli` exit"],
  ["Claude prompt", "Kiro prompt"],
  ["claude process", "kiro-cli process"],
  ["`claude` interaction", "`kiro-cli` interaction"],
  ["with claude as the sole pane", "with kiro-cli as the sole pane"],
  ["claude = 50%", "kiro-cli = 50%"],
  ["the claude pane", "the kiro-cli pane"],
  ["claude's TTY (claude detects", "kiro-cli's TTY (it detects"],
  ["`CLAUDE.md`/`AGENTS.md`", "`AGENTS.md` + `.kiro/steering/`"],
  ["CLAUDE.md / AGENTS.md", "AGENTS.md / .kiro/steering"],
  ["CLAUDE.md", "AGENTS.md"],
  ["~/.claude/skills/", ".kiro/skills/"],
  [".claude/skills/", ".kiro/skills/"],
  [".claude/worktrees", ".kiro/worktrees"],
];

const KIRO_NOTE = (name) => `
> **Kiro runtime notes** — generated by \`npm run kiro:sync\` from \`.claude/skills/${name}/\`. Edit the source, then re-sync.
> - "Skill tool" / "invoke the \`x\` skill" → activate the skill by name (\`/x\` in chat, or let Kiro auto-activate it from its description).
> - "Agent tool", "\`general-purpose\` subagent", "spawn a subagent" → delegate to the \`fdd-worker\` custom agent as a **sub-agent**, one sub-agent per skill invocation, with the same prompt and the same JSON return contract.
> - \`CLAUDE.md\` → \`AGENTS.md\` plus \`.kiro/steering/\`. \`.claude/\` paths → \`.kiro/\`.
> - Headless / parallel teams: \`kiro-cli chat --agent fdd --no-interactive --trust-all-tools "<prompt>"\`.
`;

function walk(dir) {
  return readdirSync(dir).flatMap((entry) => {
    const full = join(dir, entry);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}

function transform(text, relPath, skillName) {
  let out = text;
  for (const [from, to] of REPLACEMENTS) out = out.split(from).join(to);
  if (relPath.endsWith("SKILL.md")) out = injectNote(out, skillName);
  return out;
}

function injectNote(text, skillName) {
  const match = text.match(/^---\n[\s\S]*?\n---\n/);
  if (!match) return KIRO_NOTE(skillName) + text;
  return match[0] + KIRO_NOTE(skillName) + text.slice(match[0].length);
}

const outputs = new Map();

function emit(path, content, mode) {
  outputs.set(path, { content, mode });
}

function syncSkills() {
  for (const name of Object.keys(pkg.fdd.skills.local)) {
    const from = resolve(SRC, "skills", name);
    for (const file of walk(from)) {
      const rel = relative(from, file);
      const buffer = readFileSync(file);
      const isText = TEXT_TRANSFORM_FILES.test(`${name}/${rel}`);
      const content = isText ? transform(buffer.toString("utf8"), rel, name) : buffer;
      emit(resolve(DST, "skills", name, rel), content, statSync(file).mode);
    }
  }
}

function syncCommandsAsManualSteering() {
  const dir = resolve(SRC, "commands");
  for (const file of readdirSync(dir).filter((f) => extname(f) === ".md")) {
    const raw = readFileSync(join(dir, file), "utf8");
    const body = raw.replace(/^---\n[\s\S]*?\n---\n/, "");
    const description = (raw.match(/^description:\s*(.+)$/m) ?? [])[1] ?? "";
    const text = transform(body, file, file)
      .split("$ARGUMENTS").join("the text the user typed after the slash command (may be empty)");
    emit(resolve(DST, "steering", file),
      `---\ninclusion: manual\n---\n\n<!-- Generated by npm run kiro:sync from .claude/commands/${file}. Run it as /${file.replace(/\.md$/, "")} in Kiro chat. -->\n\n> ${description}\n${text}`);
  }
}

function syncUiDesignAgent() {
  const src = readFileSync(resolve(SRC, "agents", "frontend-ui-design.md"), "utf8");
  emit(resolve(DST, "steering", "frontend-ui-design.md"),
    `---\ninclusion: manual\n---\n\n<!-- Generated by npm run kiro:sync from .claude/agents/frontend-ui-design.md. Also used as the prompt resource of the frontend-ui-design custom agent. -->\n\n${src}`);
}

syncSkills();
syncCommandsAsManualSteering();
syncUiDesignAgent();

let drift = 0;
for (const [path, { content, mode }] of outputs) {
  const current = existsSync(path) ? readFileSync(path) : null;
  const next = Buffer.isBuffer(content) ? content : Buffer.from(content);
  if (current && current.equals(next)) continue;
  drift += 1;
  if (check) { console.log(`drift: ${relative(ROOT, path)}`); continue; }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, next);
  if (mode) chmodSync(path, mode & 0o777);
}

if (!check) {
  // Remove files of local skills that no longer exist in the source.
  for (const name of Object.keys(pkg.fdd.skills.local)) {
    const dir = resolve(DST, "skills", name);
    if (!existsSync(dir)) continue;
    for (const file of walk(dir)) if (!outputs.has(file)) rmSync(file);
  }
}

console.log(check
  ? (drift === 0 ? "✓ .kiro is in sync with .claude" : `✗ ${drift} file(s) out of sync — run npm run kiro:sync`)
  : `✓ kiro:sync wrote ${drift} file(s) (${outputs.size} derived files total)`);
if (check && drift > 0) process.exit(1);
